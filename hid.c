void hid_kbd(unsigned char *out, unsigned mods, const unsigned char keys[6])
{
	out[0] = 1; out[1] = (unsigned char) mods; out[2] = 0;
	memcpy(out + 3, keys, 6);
}

void hid_mouse(unsigned char *out, unsigned buttons, int dx, int dy, int wheel)
{
	out[0] = 2; out[1] = (unsigned char) buttons;
	out[2] = (unsigned char) (signed char) dx; out[3] = (unsigned char) (signed char) dy;
	out[4] = (unsigned char) (signed char) wheel;
}
